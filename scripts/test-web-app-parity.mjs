import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context);}catch(error){if(error.code==='ERR_MODULE_NOT_FOUND'&&specifier.startsWith('.')&&context.parentURL?.includes('/src/'))return next(`${specifier}.ts`,context);throw error;}}});
globalThis.fetch=()=>{throw new Error('No network in parity unit checks');};
const {placeCalendarFile,calendarInstant,localPlaceName}=await import('../src/lib/place-calendar.ts');
const {bookingAndroidIntent}=await import('../src/lib/booking-app-link.ts');
const trip={id:'trip-fixture',title:'일본 여행',start_date:'2026-09-19'};
const stop={id:'stop-fixture',name:'후쿠오카 숙소',map_query:'UNPLAN Fukuoka',day:1,time:'10:00',lat:33.59,lng:130.4};
assert.equal(localPlaceName(stop),'UNPLAN Fukuoka');assert.equal(localPlaceName({...stop,map_query:'  '}),stop.name);
const timed=placeCalendarFile(trip,stop,'Asia/Tokyo',new Date('2026-09-18T00:00:00Z'));
assert.ok(timed.content.includes('DTSTART:20260919T010000Z\r\nDTEND:20260919T020000Z'));
assert.ok(timed.content.includes('LOCATION:UNPLAN Fukuoka'));
const day0=placeCalendarFile(trip,{...stop,day:0,time:null},'Asia/Seoul');
assert.ok(day0.content.includes('DTSTART;VALUE=DATE:20260918\r\nDTEND;VALUE=DATE:20260919'));
assert.equal(placeCalendarFile({...trip,start_date:null},stop,'Asia/Seoul'),null);
assert.equal(calendarInstant('2026-11-01','01:30','America/New_York').toISOString(),'2026-11-01T05:30:00.000Z');
assert.equal(calendarInstant('2026-03-08','02:30','America/New_York').toISOString(),'2026-03-08T07:30:00.000Z');
const hostile=placeCalendarFile(trip,{...stop,name:'여행'.repeat(90)+'\r\nBEGIN:VEVENT;unsafe,\\'},'Asia/Seoul').content;
assert.equal(hostile.split('\r\n').filter(line=>line==='BEGIN:VEVENT').length,1);
for(const line of hostile.split('\r\n'))assert.ok(Buffer.byteLength(line)<=75);
assert.ok(hostile.replace(/\r\n /g,'').includes('\\nBEGIN:VEVENT\\;unsafe\\,\\\\'));
const raw='https://kr.trip.com/order/hotel?orderId=A%3BB&name=%ED%98%B8%ED%85%94';
const intent=bookingAndroidIntent(raw);assert.ok(intent.includes('package=ctrip.english;'));
const fallback=decodeURIComponent(intent.match(/S.browser_fallback_url=([^;]+)/)[1]);
assert.equal(new URL(fallback).searchParams.get('orderId'),'A;B');assert.equal(new URL(fallback).searchParams.get('wkp'),'1');
assert.equal(bookingAndroidIntent('https://trip.com.evil.test/order'),null);
assert.equal(bookingAndroidIntent('javascript:alert(1)'),null);
assert.equal(bookingAndroidIntent('https://user:pass@trip.com/order'),null);
assert.equal(bookingAndroidIntent('https://trip.com/order#details'),null,'fragment destinations keep exact HTTPS link');
for(const [domain,pkg]of[['www.agoda.com','com.agoda.mobile.consumer'],['www.booking.com','com.booking'],['www.airbnb.co.kr','com.airbnb.android'],['www.expedia.co.kr','com.expedia.bookings']])assert.ok(bookingAndroidIntent(`https://${domain}/reservation`).includes(`package=${pkg};`));
console.log('Web/app parity: ICS UTC/all-day/Day 0/DST/UTF-8/injection, local-name selection, booking package allowlist and exact fallback passed.');
