import {expect} from '@playwright/test';
import assert from 'node:assert/strict';
export async function checkWebManagement({page,origin,management,pdfBody,output,label,tripId,resetLedger,getLedger}) {
  await page.goto(`${origin}/workspace-offline-check?view=manage`,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'PDF 추가',exact:true}).click();
  const editor=page.getByRole('region',{name:'PDF 편집',exact:true});
  await editor.getByLabel('PDF 파일',{exact:true}).setInputFiles({name:'attached-fixture.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdfBody)});
  await editor.getByRole('button',{name:'PDF 보기: attached-fixture.pdf',exact:true}).click();
  const preview=page.getByRole('dialog',{name:'attached-fixture.pdf',exact:true});
  await expect(preview.getByRole('img',{name:'attached-fixture.pdf · 1페이지'})).toBeVisible();
  await preview.getByRole('button',{name:'PDF 미리보기 닫기',exact:true}).click();
  await editor.getByRole('checkbox',{name:/콜로세움/}).check();
  management.failure=true;await editor.getByRole('button',{name:'PDF 저장',exact:true}).click();
  await expect(editor.getByRole('alert')).toContainText('PDF 저장 실패');
  await expect(editor.getByRole('checkbox',{name:/콜로세움/})).toBeChecked();
  management.failure=false;await editor.getByRole('button',{name:'PDF 저장',exact:true}).click();
  await expect(editor).toHaveCount(0);assert.deepEqual(management.documents[0].stopIds,['A']);
  await page.getByRole('button',{name:'장소 연결 수정',exact:true}).click();
  await editor.getByRole('checkbox',{name:/트레비 분수/}).check();
  await editor.getByRole('button',{name:'PDF 저장',exact:true}).click();await expect(editor).toHaveCount(0);
  assert.deepEqual(management.documents[0].stopIds,['A','B']);
  await page.getByRole('button',{name:'예약',exact:true}).click();
  await page.getByRole('button',{name:'예약 추가',exact:true}).click();
  const reservation=page.getByRole('form',{name:'예약 편집',exact:true});
  await reservation.getByLabel('예약 이름',{exact:true}).fill('테스트 숙소');
  await reservation.getByLabel('예약 페이지 (HTTPS)',{exact:true}).fill('https://kr.trip.com/order/hotel?orderId=fixture');
  await reservation.getByLabel('예약 상태',{exact:true}).selectOption('confirmed');
  await reservation.getByLabel('결제 상태',{exact:true}).selectOption('partial');
  await reservation.getByRole('checkbox',{name:/콜로세움/}).check();
  await reservation.getByRole('checkbox',{name:'attached-fixture.pdf',exact:true}).check();
  await reservation.getByRole('button',{name:'예약 저장',exact:true}).click();await expect(reservation).toHaveCount(0);
  assert.equal(management.reservations.entries[0].paymentStatus,'partial');assert.equal(management.reservations.entries[0].bookingStatus,'confirmed');
  await page.getByRole('button',{name:'예약 수정',exact:true}).click();
  await reservation.getByLabel('예약 이름',{exact:true}).fill('수정 초안');
  management.failure=true;await reservation.getByRole('button',{name:'예약 저장',exact:true}).click();
  await expect(reservation.getByRole('alert')).toContainText('예약 저장 실패');
  await expect(reservation.getByLabel('예약 이름',{exact:true})).toHaveValue('수정 초안');
  management.failure=false;management.reservations.revision++;management.reservations.entries[0].name='다른 기기 예약';
  await reservation.getByRole('button',{name:'예약 저장',exact:true}).click();
  await expect(reservation.getByRole('alert')).toContainText('다른 곳에서 예약이 변경');
  await expect(reservation.getByRole('button',{name:'예약 저장',exact:true})).toBeDisabled();
  await reservation.getByRole('button',{name:'최신 예약으로 교체',exact:true}).click();
  await expect(reservation.getByLabel('예약 이름',{exact:true})).toHaveValue('다른 기기 예약');
  await reservation.getByLabel('예약 이름',{exact:true}).fill('동기화 예약');
  await reservation.getByRole('button',{name:'예약 저장',exact:true}).click();await expect(reservation).toHaveCount(0);
  await expect(page.getByRole('link',{name:'예산에 연결',exact:true})).toHaveAttribute('href',`/app/${tripId}/cost?reservationId=${management.reservations.entries[0].id}`);
  await page.screenshot({path:new URL(`management-${label}.png`,output).pathname,fullPage:true});
  await page.getByRole('button',{name:'변경 이력',exact:true}).click();
  await page.getByRole('button',{name:/변경 내용 보기/}).click();
  const change=page.getByRole('region',{name:'변경 내용',exact:true});
  await expect(change).toContainText('동기화 예약');
  management.latest='2';await change.getByRole('button',{name:'이 변경 되돌리기',exact:true}).click();
  await expect(page.getByRole('region',{name:'변경 이력',exact:true}).getByRole('alert')).toContainText('최신 변경 이력');assert.equal(management.undoCalls,0);
  await change.getByRole('button',{name:'최신 내용 다시 검토',exact:true}).click();
  await change.getByRole('button',{name:'이 변경 되돌리기',exact:true}).click();
  await expect(page.getByText('선택한 변경을 되돌렸습니다.',{exact:true})).toBeVisible();assert.equal(management.undoCalls,1);
  resetLedger();
  await page.goto(`${origin}/workspace-offline-check?view=linked-budget`,{waitUntil:'networkidle'});
  await expect(page.getByRole('textbox',{name:'지출 항목 이름',exact:true})).toHaveValue('연결 예약');
  await page.getByRole('spinbutton',{name:'지출 금액',exact:true}).fill('10000');
  await page.getByRole('button',{name:'항목 추가',exact:true}).click();
  await expect.poll(()=>getLedger().entries.length).toBe(1);
  assert.equal(getLedger().entries[0].reservationId,'00000000-0000-4000-8000-000000000444');
  assert.equal(getLedger().entries[0].paid,true);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'management/budget fit viewport');
}
